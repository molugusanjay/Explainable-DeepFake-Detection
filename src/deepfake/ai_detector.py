import logging
from PIL import Image

_classifier = None

def get_ai_classifier():
    global _classifier
    if _classifier is None:
        try:
            from transformers import pipeline
            # Load a pre-trained model specifically designed to detect AI-generated images
            _classifier = pipeline("image-classification", model="umm-maybe/AI-image-detector")
        except Exception as e:
            logging.warning(f"Failed to load HuggingFace AI detector: {e}")
            _classifier = "FAILED"
    return _classifier

def detect_ai_generation(image):
    """
    Analyzes the full image to determine if it was generated by an AI (Midjourney, Gemini, etc.).
    Returns a string detailing the findings.
    """
    classifier = get_ai_classifier()
    if classifier == "FAILED":
        return "Visual AI generation detection is unavailable."
    
    try:
        if not isinstance(image, Image.Image):
            image = Image.open(image).convert("RGB")
        
        results = classifier(image)
        # Results look like [{'label': 'artificial', 'score': 0.99}, {'label': 'human', 'score': 0.01}]
        
        artificial_score = 0.0
        for res in results:
            if res['label'] == 'artificial':
                artificial_score = res['score']
                break
        
        # Only flag as AI-generated if confidence is HIGH (>=75%).
        # A 20-50% score is too ambiguous — real photos shot with modern phones/cameras
        # can score in that range due to post-processing and image compression.
        if artificial_score >= 0.75:
            return f"⚠️ STRONG VISUAL AI SIGNATURE DETECTED: This image appears to be purely AI-generated (Confidence: {artificial_score:.1%})."
        else:
            return f"No strong visual AI generation signatures detected (AI-generated score: {artificial_score:.1%})."
            
    except Exception as e:
        logging.warning(f"Failed to analyze image for AI generation: {e}")
        return "Failed to run visual AI detection."
